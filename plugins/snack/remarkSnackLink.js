const {snackUrl} = require('./snackUrl');

const WEB_LINK_TEXT = 'Try it on web';

function attribute(name, value) {
  return {type: 'mdxJsxAttribute', name, value};
}

function button(label, href, variant, extraAttributes = []) {
  return {
    type: 'mdxJsxTextElement',
    name: 'a',
    attributes: [
      attribute('className', `button button--${variant} button--sm margin-right--sm`),
      attribute('href', href),
      ...extraAttributes,
    ],
    children: [{type: 'text', value: label}],
  };
}

function isWebLink(node) {
  return node.type === 'link' && node.children[0]?.value === WEB_LINK_TEXT;
}

/** Removes the "Try it on web" link, which ends the description paragraph, and returns its URL. */
function takeWebLink(tree) {
  const index = tree.children.findIndex(
    (node) => node.type === 'paragraph' && node.children.some(isWebLink),
  );
  if (index < 0) return {};
  const paragraph = tree.children[index];
  const url = paragraph.children.find(isWebLink).url;
  paragraph.children = paragraph.children.filter((node) => !isWebLink(node));
  const last = paragraph.children[paragraph.children.length - 1];
  if (last?.type === 'text') last.value = last.value.trimEnd();
  if (paragraph.children.every((node) => node.type === 'text' && !node.value)) {
    tree.children.splice(index, 1);
    return {url, index};
  }
  return {url, index: index + 1};
}

/**
 * Turns the "Try it on web" link of example pages into a "Run on web" button, and adds an
 * "Edit in Snack" button next to it when the example's `snack_supported` front matter is true.
 */
module.exports = function remarkSnackLink() {
  return (tree, file) => {
    const customProps = file.data.frontMatter?.custom_props || {};
    const relPath = customProps.example_rel_path;
    if (!relPath || !tree.children.some((node) => node.type === 'code')) return;

    const {url: webUrl, index: webLinkIndex} = takeWebLink(tree);
    // Pages generated by rnmapbox/maps before snack_supported existed fall back to webSupported.
    const snackSupported = customProps.snack_supported ?? webUrl != null;

    const codeIndex = tree.children.findIndex((node) => node.type === 'code');
    let snack = null;
    if (snackSupported) {
      snack = snackUrl(relPath, tree.children[codeIndex].value);
      if (!snack && customProps.snack_supported) {
        throw new Error(`${relPath} has snack_supported but imports files the Snack can't load`);
      }
    }

    const buttons = [];
    if (webUrl) buttons.push(button('Run on web', webUrl, 'secondary'));
    if (snack) {
      buttons.push(
        button('Edit in Snack', snack, 'primary', [
          attribute('target', '_blank'),
          attribute('rel', 'noopener noreferrer'),
          attribute('title', 'Runs the web version of this example in Expo Snack'),
        ]),
      );
    }
    if (!buttons.length) return;

    const row = {type: 'mdxJsxFlowElement', name: 'p', attributes: [], children: buttons};
    tree.children.splice(webLinkIndex ?? codeIndex, 0, row);
  };
};
